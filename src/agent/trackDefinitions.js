export function getProgressionDesignations(progress) {
  return new Set(
    progressionTracks.flatMap((track) =>
      track.labels
        .slice(0, progress[track.id] ?? 0)
        .filter(Boolean)
        .map((designation) => designation.toLowerCase()),
    ),
  );
}
